#@title Драйверы выручки (верхнеуровнево) - выручка = средний чек * на количество чеков

# Абсолютные метрики
revenue_by_year = (
    fact_sales
    .groupby('год')
    .agg(
        выручка=('сумма_строки', 'sum'),
        количество_чеков=('id_чека', 'nunique')
    )
    .reset_index()
)

# Средний чек
revenue_by_year['средний_чек'] = revenue_by_year['выручка'] / revenue_by_year['количество_чеков']

# Округляем
revenue_by_year['выручка'] = revenue_by_year['выручка'].round(2)
revenue_by_year['средний_чек'] = revenue_by_year['средний_чек'].round(2)

print("Абсолютные метрики по годам:")
display(revenue_by_year)

# Динамика относительно 2024 года (в %)

base_2024 = revenue_by_year.loc[revenue_by_year['год'] == 2024].iloc[0]

growth_metrics = (
    revenue_by_year
    .assign(
        рост_выручки_pct=lambda x: ((x['выручка'] - base_2024['выручка']) / base_2024['выручка']) * 100.00,
        рост_количества_чеков_pct=lambda x: ((x['количество_чеков'] - base_2024['количество_чеков']) / base_2024['количество_чеков']) * 100.00,
        рост_среднего_чека_pct=lambda x: ((x['средний_чек'] - base_2024['средний_чек']) / base_2024['средний_чек']) * 100.00
    )
)

# Для 2024 года ставим 0%
growth_metrics.loc[growth_metrics['год'] == 2024, ['рост_выручки_pct', 'рост_количества_чеков_pct', 'рост_среднего_чека_pct']] = 0.00

# Округление
growth_metrics[['рост_выручки_pct', 'рост_количества_чеков_pct', 'рост_среднего_чека_pct']] = (
    growth_metrics[['рост_выручки_pct', 'рост_количества_чеков_pct', 'рост_среднего_чека_pct']].round(2)
)

print("Динамика относительно 2024 года (%):")
display(growth_metrics[['год', 'рост_выручки_pct', 'рост_количества_чеков_pct', 'рост_среднего_чека_pct']])

